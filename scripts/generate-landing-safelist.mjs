#!/usr/bin/env node
// Tailwind scans source files. A store's landing content lives in D1, so the
// classes it uses are invisible to the scanner and their utilities never reach
// the bundle - the page renders with the markup but none of the styling.
//
// This dumps every class used by the store's landing sections into a file that
// storefront.css declares as an @source. Run it after editing landing content,
// then rebuild.
//
//   node scripts/generate-landing-safelist.mjs <d1-database-name>
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const db = process.argv[2];
if (!db) {
  console.error('usage: node scripts/generate-landing-safelist.mjs <d1-database-name>');
  process.exit(1);
}

const out = execFileSync(
  'npx',
  ['wrangler', 'd1', 'execute', db, '--remote', '--json', '--command',
   "SELECT content_html FROM landing_sections WHERE content_html IS NOT NULL;"],
  { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
);

const match = out.match(/\[\s*\{[\s\S]*\}\s*\]/);
if (!match) {
  console.error('could not parse wrangler output');
  process.exit(1);
}
const rows = JSON.parse(match[0])[0]?.results ?? [];

const classes = new Set();
for (const row of rows) {
  for (const m of String(row.content_html ?? '').matchAll(/class="([^"]+)"/g)) {
    for (const c of m[1].split(/\s+/)) {
      // astro-* are per-component scoping hashes, not utilities
      if (c && !c.startsWith('astro-')) classes.add(c);
    }
  }
}

const sorted = [...classes].sort();
writeFileSync(
  'src/styles/landing-safelist.html',
  '<!-- Generated by scripts/generate-landing-safelist.mjs. Do not edit by hand.\n' +
  '     Every class the store\'s D1 landing content uses, so Tailwind emits their\n' +
  '     utilities. Regenerate after changing landing content, then rebuild. -->\n' +
  `<div class="${sorted.join(' ')}"></div>\n`,
);
console.log(`landing safelist: ${sorted.length} classes from ${rows.length} sections`);
